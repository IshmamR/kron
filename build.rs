//! Generates `src/database/schema.rs`'s tables and columns from the
//! migrations, so a command naming a column that doesn't exist, or giving it
//! a value of the wrong type, fails to compile. See docs/storage.md.

use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use rusqlite::Connection;

const MIGRATIONS: &str = "src/database/migrations";

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed={MIGRATIONS}");
    let directory = Path::new(&env::var("CARGO_MANIFEST_DIR")?).join(MIGRATIONS);
    let kron = migrations(&directory, "kron")?;
    let device = migrations(&directory, "device")?;

    let mut code = String::from("// Generated by build.rs from the migrations. Don't edit.\n\n");
    write_migrations(&mut code, "KRON_MIGRATIONS", &kron)?;
    write_migrations(&mut code, "DEVICE_MIGRATIONS", &device)?;
    let kron_tables = tables(&migrated(&kron)?)?;
    writeln!(code, "/// Every kron.sqlite table `Write` writes.")?;
    writeln!(code, "pub const TABLES: &[&str] = &[")?;
    for table in &kron_tables {
        writeln!(code, "    {:?},", table.name)?;
    }
    writeln!(code, "];\n")?;
    for table in &kron_tables {
        write_table(&mut code, table, false)?;
    }
    for table in &tables(&migrated(&device)?)? {
        write_table(&mut code, table, true)?;
    }
    fs::write(Path::new(&env::var("OUT_DIR")?).join("schema.rs"), code)?;
    Ok(())
}

/// An in-memory database with these migrations applied.
fn migrated(paths: &[PathBuf]) -> Result<Connection, Box<dyn Error>> {
    let connection = Connection::open_in_memory()?;
    for path in paths {
        connection
            .execute_batch(&fs::read_to_string(path)?)
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(connection)
}

struct Table {
    name: String,
    /// In key order.
    key: Vec<Column>,
    columns: Vec<Column>,
}

struct Column {
    name: String,
    /// As declared: STRICT allows only INT, INTEGER, REAL, TEXT, BLOB and ANY.
    declared: String,
    not_null: bool,
}

/// `NNNN_{database}.sql`, numbered from 1 with no gaps, in order. A
/// database's `user_version` is how many it has had, so never edit one that
/// has shipped: add the next.
fn migrations(directory: &Path, database: &str) -> Result<Vec<PathBuf>, Box<dyn Error>> {
    let suffix = format!("_{database}.sql");
    let mut numbered = Vec::new();
    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        if let Some(number) = name.strip_suffix(&suffix) {
            let number: usize = number
                .parse()
                .map_err(|_| format!("{name}: expected NNNN{suffix}"))?;
            numbered.push((number, path));
        }
    }
    numbered.sort();
    for (expected, (number, path)) in (1..).zip(&numbered) {
        if *number != expected {
            return Err(format!("{}: expected migration {expected}", path.display()).into());
        }
    }
    Ok(numbered.into_iter().map(|(_, path)| path).collect())
}

/// The tables `Write` writes: views, FTS5's tables and the outbox are left out.
fn tables(connection: &Connection) -> Result<Vec<Table>, Box<dyn Error>> {
    let names = connection
        .prepare(
            "SELECT name, strict FROM pragma_table_list
             WHERE schema = 'main' AND type = 'table'
               AND name NOT LIKE 'sqlite_%' AND name != 'outbox'
             ORDER BY name",
        )?
        .query_map([], |row| {
            Ok((row.get::<_, String>(0)?, row.get::<_, bool>(1)?))
        })?
        .collect::<Result<Vec<_>, _>>()?;
    let mut columns_of = connection
        .prepare("SELECT name, type, \"notnull\", pk FROM pragma_table_info(?1) ORDER BY cid")?;
    let mut tables = Vec::new();
    for (name, strict) in names {
        // The generated types are only as true as the column types SQLite enforces.
        if !strict {
            return Err(format!("{name} isn't STRICT").into());
        }
        let mut key = Vec::new();
        let mut columns = Vec::new();
        let rows = columns_of
            .query_map([&name], |row| {
                Ok((
                    Column {
                        name: row.get(0)?,
                        declared: row.get(1)?,
                        not_null: row.get(2)?,
                    },
                    // The column's place in the key, 0 when not in it.
                    row.get::<_, i64>(3)?,
                ))
            })?
            .collect::<Result<Vec<_>, _>>()?;
        for (column, position) in rows {
            if position > 0 {
                key.push((position, column));
            } else {
                columns.push(column);
            }
        }
        key.sort_by_key(|(position, _)| *position);
        tables.push(Table {
            name,
            key: key.into_iter().map(|(_, column)| column).collect(),
            columns,
        });
    }
    Ok(tables)
}

fn write_migrations(
    code: &mut String,
    name: &str,
    paths: &[PathBuf],
) -> Result<(), Box<dyn Error>> {
    writeln!(code, "pub(super) const {name}: &[&str] = &[")?;
    for path in paths {
        writeln!(code, "    include_str!({:?}),", path.display().to_string())?;
    }
    writeln!(code, "];\n")?;
    Ok(())
}

fn write_table(code: &mut String, table: &Table, device: bool) -> Result<(), Box<dyn Error>> {
    let type_name = camel_case(&table.name);
    let key_types = table
        .key
        .iter()
        .map(|column| Ok(format!("{},", value_type(&table.name, column)?)))
        .collect::<Result<String, Box<dyn Error>>>()?;
    let key_names = table
        .key
        .iter()
        .map(|column| format!("{:?}", column.name))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(code, "/// `{}`.", table.name)?;
    writeln!(code, "#[derive(Clone, Copy, Debug)]")?;
    writeln!(code, "pub struct {type_name};\n")?;
    writeln!(code, "impl Table for {type_name} {{")?;
    writeln!(code, "    const NAME: &'static str = {:?};", table.name)?;
    writeln!(
        code,
        "    const KEY: &'static [&'static str] = &[{key_names}];"
    )?;
    writeln!(code, "    type Key = ({key_types});")?;
    if device {
        writeln!(code, "    const DEVICE: bool = true;")?;
    }
    writeln!(code, "}}\n")?;
    if table
        .columns
        .iter()
        .any(|column| column.name == "deleted_at")
    {
        writeln!(code, "impl SoftDelete for {type_name} {{}}\n")?;
    }
    if table.columns.is_empty() {
        return Ok(());
    }

    writeln!(code, "/// `{}`'s columns, but its key.", table.name)?;
    writeln!(code, "pub mod {} {{", table.name)?;
    writeln!(code, "    use super::*;\n")?;
    for column in &table.columns {
        let value = value_type(&table.name, column)?;
        let value = if column.not_null {
            value
        } else {
            format!("Nullable<{value}>")
        };
        let null = if column.not_null { " NOT NULL" } else { "" };
        writeln!(code, "    /// `{} {}{null}`", column.name, column.declared)?;
        writeln!(
            code,
            "    pub const {}: Column<{type_name}, {value}> = Column::new({:?});",
            column.name.to_uppercase(),
            column.name
        )?;
    }
    writeln!(code, "}}\n")?;
    Ok(())
}

fn value_type(table: &str, column: &Column) -> Result<String, Box<dyn Error>> {
    let value = match column.declared.as_str() {
        "INT" | "INTEGER" => "Integer",
        "REAL" => "Real",
        "TEXT" => "Text",
        "BLOB" => "Blob",
        other => return Err(format!("{table}.{}: no Rust type for {other}", column.name).into()),
    };
    Ok(value.to_string())
}

/// `fact_overrides` → `FactOverrides`.
fn camel_case(name: &str) -> String {
    name.split('_')
        .map(|word| {
            let mut characters = word.chars();
            characters
                .next()
                .map(|first| first.to_uppercase().chain(characters).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}
